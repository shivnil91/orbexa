export function messageFor(locale: string, code: string | undefined): string | null {
  if (!code) {
    return null;
  }
  const messages = getCatalog(locale).messages;
  return messages[`form.${code}`] ?? messages["form.generic"] ?? null;
}

const catalogs: Record<string, Catalog> = { en };

export function getCatalog(locale: string): Catalog {
  return catalogs[locale] ?? catalogs.en;
}

export function t(locale: string, key: string, vars?: Record<string, string>): string {
  const template = getCatalog(locale).messages[key];
  if (!template) {
    throw new Error(`missing message ${key}`);
  }
  if (!vars) {
    return template;
  }
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, value),
    template,
  );
}
